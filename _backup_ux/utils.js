// ─── Авто-определение проекционных координат ───────────────────────────────
// Возвращает { zone, candidates[] } или null если координаты геодезические
function detectProjectedMSK(rawText) {
  const lines = rawText.trim().split('\n').filter(l => {
    const t = l.trim();
    return t && !t.startsWith('#') && !t.startsWith('//');
  });
  if (!lines.length) return null;

  const pairs = [];
  for (const line of lines) {
    const nums = line.match(/-?\d+(?:[.,]\d+)?/g);
    if (!nums || nums.length < 2) continue;
    const a = parseFloat(nums[0].replace(',', '.'));
    const b = parseFloat(nums[1].replace(',', '.'));
    if (isFinite(a) && isFinite(b)) pairs.push([a, b]);
  }
  if (!pairs.length) return null;

  const maxA = Math.max(...pairs.map(p => Math.abs(p[0])));
  const maxB = Math.max(...pairs.map(p => Math.abs(p[1])));
  if (maxA <= 90 && maxB <= 180) return null; // явно геодезические

  // Определяем зону по старшей цифре значения восточного (Y) координаты
  const aZone = Math.floor(maxA / 1_000_000);
  const bZone = Math.floor(maxB / 1_000_000);
  // Y (easting) содержит префикс зоны 1–9; выбираем наибольшее из двух
  const zone = bZone >= 1 && bZone <= 9 ? bZone : (aZone >= 1 && aZone <= 9 ? aZone : null);

  const candidates = CRS_DB.filter(c => {
    if (!c.p4 || c.p4 === 'custom' || c.x0 === null) return false;
    const cz = Math.floor(c.x0 / 1_000_000);
    return zone !== null ? cz === zone : true;
  });

  return { zone, candidates };
}

// ─── Трансформация двух числовых значений → [lat, lon] WGS84 ──────────────
// Входной формат: X (northing), Y (easting) — стандарт российской геодезии
// Автоматически пробует оба порядка если первый дал не-Россию
function transformToWGS84(a, b, crs) {
  if (!crs || !crs.p4 || crs.p4 === 'custom') return null;
  try {
    // Стандарт: a = X (northing), b = Y (easting) → proj4([easting, northing])
    const r1 = proj4(crs.p4, 'WGS84', [b, a]);
    if (_inRussia(r1[1], r1[0])) return [r1[1], r1[0]];
    // Альтернатива: a = Y (easting), b = X (northing)
    const r2 = proj4(crs.p4, 'WGS84', [a, b]);
    if (_inRussia(r2[1], r2[0])) return [r2[1], r2[0]];
  } catch (_) {}
  return null;
}
function _inRussia(lat, lon) {
  return lat >= 40 && lat <= 83 && lon >= 18 && lon <= 200;
}

