// УНИВЕРСАЛЬНЫЙ ПАРСЕР КООРДИНАТ
// Форматы:
//   DD:    "55.123456 37.654321" | "37.456, 55.123" (авто-порядок lat/lon)
//   ГМС:   "55°12′34.56″N 37°39′15.56″E" (символы °′″ и их аналоги)
//   ГДМ:   "55°12.576′N 37°39.259′E"
//   N/S/E/W: "N55.123 E37.456" | "55.123N 37.456E"
//   6 чисел ГМС: "55 12 34.56 37 39 15.56"
//   4 числа ГДМ: "55 12.576 37 39.259"
//   WKT:   "POINT(37.654321 55.123456)"  (lon lat по стандарту OGC)
//   Авто:  если |первое значение| > 90 — считается долготой, меняем порядок
// ══════════════════════════════════════════════════════════════════════════════

function parseCoordLine(line) {
  line = (line || '').trim().replace(/\r/g, '');
  if (!line || line.startsWith('#') || line.startsWith('//')) return null;

  // ─── WKT POINT(lon lat) по стандарту OGC ────────────────────────────────
  const wkt = line.match(/^POINT\s*\(\s*(-?[\d.]+)\s+(-?[\d.]+)\s*\)/i);
  if (wkt) {
    const a = parseFloat(wkt[1]), b = parseFloat(wkt[2]);
    return (isFinite(a) && isFinite(b)) ? [b, a] : null; // lon lat → [lat, lon]
  }

  // ─── Нормализация типографских символов ─────────────────────────────────
  let s = line
    .replace(/[°º]/g, '°')
    .replace(/[′ʹ´`\u2018\u2019\u02BC'']/g, "'")
    .replace(/[″\u201C\u201D""]/g, '"');

  // ─── DMS/DDM с символом ° ───────────────────────────────────────────────
  if (s.includes('°')) return _parseDegreeLine(s);

  // ─── Токенизируем числа с возможными полусферами N/S/E/W ────────────────
  const items = _tokenizeCoords(s);
  const nums  = items.map(x => x.v);
  if (nums.length < 2) return null;

  if (nums.length === 2) {
    return _assignPair(items[0].v, items[1].v, items[0].h, items[1].h);
  }
  if (nums.length === 4 && nums[1] < 60 && nums[3] < 60) {
    // ГДМ: [Г М] [Г М]
    const a = nums[0] + nums[1] / 60;
    const b = nums[2] + nums[3] / 60;
    return _assignPair(a, b, items[0].h || items[1].h, items[2].h || items[3].h);
  }
  if (nums.length === 6 && nums[1] < 60 && nums[2] < 60 && nums[4] < 60 && nums[5] < 60) {
    // ГМС: [Г М С] [Г М С]
    const a = nums[0] + nums[1] / 60 + nums[2] / 3600;
    const b = nums[3] + nums[4] / 60 + nums[5] / 3600;
    return _assignPair(a, b,
      items[0].h || items[1].h || items[2].h,
      items[3].h || items[4].h || items[5].h);
  }

  // Фолбэк: берём первые два числа как DD
  return _assignPair(items[0].v, items[1].v, items[0].h, items[1].h);
}

// Токенизация: извлекает [{v: число, h: 'N'|'S'|'E'|'W'|''}] в порядке появления
function _tokenizeCoords(s) {
  const re = /([NSEW])?\s*(-?\d+(?:[.,]\d+)?)\s*([NSEW])?/gi;
  const items = [];
  let m;
  while ((m = re.exec(s)) !== null) {
    const v = parseFloat((m[2] || '').replace(',', '.'));
    if (!isFinite(v)) continue;
    // Используем ведущую полусферу (m[1]) приоритетно, затем замыкающую (m[3])
    items.push({ v, h: (m[1] || m[3] || '').toUpperCase() });
  }
  return items;
}

// Назначает lat/lon по полусферам; без полусфер — авто-порядок (|a|>90 → lon)
function _assignPair(a, b, hA, hB) {
  hA = (hA || '').toUpperCase();
  hB = (hB || '').toUpperCase();
  let lat, lon;
  if (hA === 'N' || hA === 'S') {
    lat = (hA === 'S') ? -Math.abs(a) : a;
    lon = (hB === 'W') ? -Math.abs(b) : b;
  } else if (hA === 'E' || hA === 'W') {
    lon = (hA === 'W') ? -Math.abs(a) : a;
    lat = (hB === 'S') ? -Math.abs(b) : b;
  } else if (hB === 'N' || hB === 'S') {
    lat = (hB === 'S') ? -Math.abs(b) : b;
    lon = a;
  } else if (hB === 'E' || hB === 'W') {
    lon = (hB === 'W') ? -Math.abs(b) : b;
    lat = a;
  } else {
    // Нет полусфер: если |a| > 90 → a это долгота, меняем порядок
    [lat, lon] = Math.abs(a) > 90 ? [b, a] : [a, b];
  }
  return (isFinite(lat) && isFinite(lon)) ? [lat, lon] : null;
}

// Парсит строку с символом °: форматы ГМС и ГДМ
function _parseDegreeLine(s) {
  // Regex: [NSEW?] Г° [М' [С"]] [NSEW?]
  // Negative lookahead (?!\s*°): секунды не захватывают следующий градусный блок
  const re = /([NSEW])?\s*(-?\d+(?:[.,]\d+)?)°\s*(?:(\d+(?:[.,]\d+)?)'?\s*(?:(\d+(?:[.,]\d+)?)(?!\s*°)"?)?)?\s*([NSEW])?/gi;
  const parts = [];
  let m;
  while ((m = re.exec(s)) !== null) {
    const hem = (m[1] || m[5] || '').toUpperCase();
    const v   = parseFloat((m[2] || '0').replace(',', '.'))
              + (m[3] ? parseFloat(m[3].replace(',', '.')) / 60   : 0)
              + (m[4] ? parseFloat(m[4].replace(',', '.')) / 3600 : 0);
    if (!isFinite(v)) continue;
    parts.push({ v: (hem === 'S' || hem === 'W') ? -v : v, hem });
  }
  if (parts.length < 2) return null;

  let lat = null, lon = null;
  for (const p of parts) {
    if ((p.hem === 'N' || p.hem === 'S') && lat === null) lat = p.v;
    else if ((p.hem === 'E' || p.hem === 'W') && lon === null) lon = p.v;
  }
  if (lat === null || lon === null) {
    // Нет явных полусфер → авто-порядок
    const [a, b] = [parts[0].v, parts[1].v];
    [lat, lon] = Math.abs(a) > 90 ? [b, a] : [a, b];
  }
  return (isFinite(lat) && isFinite(lon)) ? [lat, lon] : null;
}


